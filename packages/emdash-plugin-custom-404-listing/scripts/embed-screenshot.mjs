// Writes assets/404_plugin.png into src/screenshot.ts as base64. The plugin
// build has no asset loader, so the screenshot route can only serve bytes that
// are part of the source. Run after replacing the PNG: `pnpm embed-screenshot`.
import { readFileSync, writeFileSync } from "node:fs";

const png = readFileSync(new URL("../assets/404_plugin.png", import.meta.url));

writeFileSync(
	new URL("../src/screenshot.ts", import.meta.url),
	`// Generated by scripts/embed-screenshot.mjs from assets/404_plugin.png. Do not edit.
export const SCREENSHOT_PNG_BASE64 =
	"${png.toString("base64")}";
`,
);
